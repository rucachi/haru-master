def get_chahye_kor_questions():
    questions = []
    q_counter = 41 # M1_KOR_041 ~ M1_KOR_090
    for p_text, chap, items in CHAHYE_KOR_PASSAGES:
        for it in items:
            questions.append({
                "question_id": f"M1_KOR_{q_counter:03d}",
                "grade": 1,
                "subject": "국어",
                "chapter": chap,
                "difficulty": "medium" if q_counter % 2 == 1 else "hard",
                "passage": p_text.strip(),
                "question_text": it[0].strip(),
                "options": it[1],
                "correct_answer": it[2],
                "explanation": it[3].strip()
            })
            q_counter += 1
    return questions

